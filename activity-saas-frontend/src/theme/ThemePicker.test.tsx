import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import ThemePicker from './ThemePicker';
import { applyTheme, defaultThemeColors } from './platformTheme';
import { api } from '../api';
vi.mock('../api', () => ({ api: { request: vi.fn() }, API_BASE: '/api' }));
if (!HTMLDialogElement.prototype.showModal) HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
if (!HTMLDialogElement.prototype.close) HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); };
afterEach(() => { cleanup(); vi.resetAllMocks(); });
it('chooses readable header text for light and dark custom header colors', () => {
  applyTheme('revspine-warm', { ...defaultThemeColors('revspine-warm'), raised: '#402020' });
  expect(document.documentElement.style.getPropertyValue('--voya-raised-text')).toBe('#fffaf6');
  applyTheme('revspine-warm', { ...defaultThemeColors('revspine-warm'), raised: '#e1cbad' });
  expect(document.documentElement.style.getPropertyValue('--voya-raised-text')).toBe('#211c15');
});
it('previews without persisting, cancels, and saves the global choice', async () => {
  vi.mocked(api.request).mockResolvedValueOnce({ theme: 'voya-midnight' }).mockResolvedValueOnce({ theme: 'revspine-warm', colors: { ...defaultThemeColors('revspine-warm'), primary: '#a04020' } });
  render(<ThemePicker />);
  await waitFor(() => expect(screen.getByRole('radio', { name: 'Warm' })).toBeEnabled());
  expect(screen.getAllByRole('radio')).toHaveLength(4);
  expect(screen.getByRole('radio', { name: 'Lagoon Light' })).toBeEnabled();
  expect(screen.getByRole('radio', { name: 'Canopy' })).toBeEnabled();
  expect(screen.queryByText(/VOYA|RevSpine/)).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('radio', { name: 'Warm' }));
  expect(document.documentElement.dataset.theme).toBe('revspine-warm');
  expect(api.request).toHaveBeenCalledTimes(1);
  fireEvent.click(screen.getByText('Cancel preview'));
  expect(document.documentElement.dataset.theme).toBe('voya-midnight');
  fireEvent.click(screen.getByRole('radio', { name: 'Warm' }));
  fireEvent.click(screen.getByRole('button', { name: /Edit Warm Primary actions/ }));
  expect(screen.getByRole('dialog', { name: 'Primary actions' })).toBeVisible();
  fireEvent.change(screen.getByLabelText('Primary actions hex value'), { target: { value: '#a04020' } });
  fireEvent.click(screen.getByRole('button', { name: 'Close color picker' }));
  fireEvent.click(screen.getByRole('button', { name: 'Apply Warm theme and colors' }));
  await screen.findByText(/Colors saved for everyone/);
  expect(api.request).toHaveBeenLastCalledWith('/admin/settings/appearance', { method: 'PATCH', body: JSON.stringify({ theme: 'revspine-warm', ...defaultThemeColors('revspine-warm'), primary: '#a04020' }) });
  expect(document.documentElement.dataset.theme).toBe('revspine-warm');
  expect(document.documentElement.style.getPropertyValue('--voya-primary')).toBe('#a04020');
  cleanup();
  expect(document.documentElement.dataset.theme).toBe('revspine-warm');
});
